-- =========================================================
-- V3: Tasks
-- Project-scoped work items with sprint and project-member assignment.
-- =========================================================

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    sprint_id BIGINT,
    assignee_id BIGINT,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    status VARCHAR(50) NOT NULL DEFAULT 'TODO',
    priority VARCHAR(50) NOT NULL DEFAULT 'MEDIUM',
    due_date DATE,
    estimated_hours NUMERIC(8,2),
    completed_at TIMESTAMP,
    task_number BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_task_project FOREIGN KEY (project_id)
        REFERENCES projects(id) ON DELETE CASCADE,
    CONSTRAINT fk_task_sprint FOREIGN KEY (sprint_id)
        REFERENCES sprints(id) ON DELETE SET NULL,
    CONSTRAINT fk_task_assignee FOREIGN KEY (assignee_id)
        REFERENCES project_members(id) ON DELETE SET NULL,
    CONSTRAINT uk_task_project_number UNIQUE (project_id, task_number),
    CONSTRAINT ck_task_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'IN_REVIEW', 'DONE', 'BLOCKED')),
    CONSTRAINT ck_task_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_task_estimated_hours CHECK (estimated_hours IS NULL OR estimated_hours >= 0)
);

CREATE INDEX idx_task_project_status ON tasks(project_id, status);
CREATE INDEX idx_task_project_priority ON tasks(project_id, priority);
CREATE INDEX idx_task_project_sprint ON tasks(project_id, sprint_id);
CREATE INDEX idx_task_assignee ON tasks(assignee_id);
CREATE INDEX idx_task_due_date ON tasks(project_id, due_date);
