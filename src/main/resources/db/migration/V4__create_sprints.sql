-- =========================================================
-- V4: Sprints
-- Project delivery iterations used to organize tasks.
-- =========================================================

CREATE TABLE sprints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    goal VARCHAR(1000),
    status VARCHAR(50) NOT NULL DEFAULT 'PLANNED',
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    capacity_hours NUMERIC(8,2),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sprint_project FOREIGN KEY (project_id)
        REFERENCES projects(id) ON DELETE CASCADE,
    CONSTRAINT uk_sprint_project_name UNIQUE (project_id, name),
    CONSTRAINT ck_sprint_status CHECK (status IN ('PLANNED', 'ACTIVE', 'COMPLETED')),
    CONSTRAINT ck_sprint_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_sprint_capacity CHECK (capacity_hours IS NULL OR capacity_hours >= 0)
);

CREATE INDEX idx_sprint_project_status ON sprints(project_id, status);
CREATE INDEX idx_sprint_project_dates ON sprints(project_id, start_date, end_date);
